USE PintureriaDB;
GO

IF EXISTS (SELECT 1 FROM dbo.MIGRACION WHERE nombre = 'NNNN_nombre')
BEGIN
    PRINT 'Migracion NNNN_nombre ya aplicada.';
    SET NOEXEC ON;
END
GO

BEGIN TRANSACTION;
BEGIN TRY
    -- Cambios idempotentes (IF NOT EXISTS / CREATE OR ALTER)

    INSERT INTO dbo.MIGRACION (nombre) VALUES ('NNNN_nombre');
    COMMIT TRANSACTION;
END TRY
BEGIN CATCH
    IF @@TRANCOUNT > 0 ROLLBACK TRANSACTION;
    THROW;
END CATCH
GO

SET NOEXEC OFF;
GO
